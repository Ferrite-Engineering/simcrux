import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:simcrux/domain/models/eqy_script.dart';
import 'package:simcrux/domain/models/formal_config.dart';
import 'package:simcrux/domain/models/formal_import_result.dart';
import 'package:simcrux/services/formal/formal_containment.dart';
import 'package:simcrux/services/import/import_yaml.dart';

/// Reads an EQY `.eqy` file into **one SimCrux test**, emitted as an
/// inspectable `simcrux.yaml` for the `eqy` driver.
///
/// ## Why one test
///
/// One `eqy` invocation is one verdict with parts: EQY partitions the two
/// designs itself, at run time, and proves each partition. The partitions
/// are not known before the run and are not independent proofs, so they
/// are reported as child rows of the one test, not enumerated up front.
///
/// ## What it emits
///
/// - `defaults.simulator: eqy` and the `string_match` detector on
///   `EqyLogReader.kPassMarker` ([writeEqyPassDetector]).
/// - One suite named after the file, one test with `formal.eqy_file`
///   (relative to the emitted file's directory when it lies below it).
/// - `top:` is the test name: a required `TestSpec` field the `.eqy` file's
///   `[gold]` and `[gate]` scripts, not SimCrux, really decide.
///
/// Nothing is run and nothing is written; the caller decides where the file
/// goes.
class EqyProjectImporter {
  /// Creates an importer. The file-system hooks are injected so tests run
  /// against an in-memory tree.
  EqyProjectImporter({
    String Function(String path)? readFile,
    bool Function(String path)? fileExists,
  }) : _readFile = readFile ?? _defaultReadFile,
       _fileExists = fileExists ?? _defaultFileExists;

  final String Function(String path) _readFile;
  final bool Function(String path) _fileExists;

  static String _defaultReadFile(String path) => File(path).readAsStringSync();

  static bool _defaultFileExists(String path) => File(path).existsSync();

  /// Imports the `.eqy` file at [path] and emits a project file for a file
  /// in [outputDirectory].
  ///
  /// [eqyBinary] lands once under `defaults.formal.eqy_binary`; the loader
  /// honours it only when project tooling is allowed.
  ///
  /// Throws [FormalImportException] when [path] is not an `.eqy` file, has
  /// no `[gold]` or `[gate]` section, or has a name that cannot name its
  /// work directory.
  FormalImportResult importFile({
    required String path,
    required String outputDirectory,
    String? eqyBinary,
  }) {
    final abs = p.normalize(p.absolute(path));
    if (!_fileExists(abs)) {
      throw FormalImportException(path: abs, message: 'No such file.');
    }
    if (p.extension(abs).toLowerCase() != '.eqy') {
      throw FormalImportException(
        path: abs,
        message: 'Not an EQY file: point at a `.eqy` file.',
      );
    }
    final base = p.basenameWithoutExtension(abs);
    final segment = FormalContainment.segmentProblem(base);
    if (segment != null) {
      throw FormalImportException(
        path: abs,
        message:
            'The file name cannot name the EQY work directory ($segment). '
            'Rename the file.',
      );
    }
    String text;
    try {
      text = _readFile(abs);
    } on Object {
      text = '';
    }
    final script = EqyScript.parse(text);
    final unlowerable = EqyScript.vhdlReads(
      text,
    ).where((r) => r.problem != null).firstOrNull;
    if (!script.hasGoldAndGate) {
      throw FormalImportException(
        path: abs,
        message:
            'Not an EQY file: it needs both a [gold] and a [gate] section.',
      );
    }
    final warnings = <FormalImportWarning>[
      if (unlowerable != null)
        FormalImportWarning(
          code: 'vhdl_plugin',
          message:
              '`${p.basename(abs)}` reads VHDL through the GHDL Yosys plugin '
              '(`${unlowerable.line}`), which SimCrux does not run, and '
              'cannot lower that line with `ghdl --synth --out=verilog`: '
              '${unlowerable.problem}. The check will not start until it '
              'reads `ghdl [--std=NN] <files> -e <unit>` in [gold] or [gate].',
        ),
      if (script.strategies.isEmpty)
        FormalImportWarning(
          code: 'no_strategy',
          message:
              '`${p.basename(abs)}` declares no [strategy] section, so EQY '
              'has no way to prove a partition and the check will not reach '
              'a verdict.',
        ),
    ];
    final outDir = p.normalize(p.absolute(outputDirectory));
    final eqyFile = p.isWithin(outDir, abs)
        ? p.relative(abs, from: outDir).replaceAll(r'\', '/')
        : abs;
    final buf = StringBuffer()
      ..writeln('# Generated by the SimCrux EQY importer.')
      ..writeln('# Source: $abs')
      ..writeln(
        '# One test: EQY partitions the designs at run time and reports each '
        'partition',
      )
      ..writeln("# on this test's row.")
      ..writeln('#')
      ..writeln(
        '# This file is yours: read it, diff it, edit it, commit it. '
        'Re-running the importer',
      )
      ..writeln('# overwrites it.');
    if (warnings.isNotEmpty) {
      buf
        ..writeln('#')
        ..writeln('# Import warnings (${warnings.length}):');
      for (final w in warnings) {
        buf.writeln('#   [${w.code}] ${w.message}');
      }
    }
    buf
      ..writeln()
      ..writeln("version: '1'")
      ..writeln()
      ..writeln('defaults:')
      ..writeln('  simulator: ${FormalConfig.kEqySimulatorId}');
    writeEqyPassDetector(buf);
    if (eqyBinary != null && eqyBinary.isNotEmpty) {
      buf
        ..writeln('  formal:')
        ..writeln('    eqy_binary: ${importYamlScalar(eqyBinary)}');
    }
    buf
      ..writeln()
      ..writeln('suites:')
      ..writeln('  ${importYamlKey(base)}:')
      ..writeln('    description: EQY equivalence check ${p.basename(abs)}.')
      ..writeln('    tests:')
      ..writeln('      - name: ${importYamlScalar(base)}')
      ..writeln('        top: ${importYamlScalar(base)}')
      ..writeln('        formal:')
      ..writeln('          eqy_file: ${importYamlScalar(eqyFile)}');
    return FormalImportResult(
      simcruxYaml: buf.toString(),
      testCount: 1,
      jobs: <String>[p.basename(abs)],
      warnings: List<FormalImportWarning>.unmodifiable(warnings),
    );
  }
}
