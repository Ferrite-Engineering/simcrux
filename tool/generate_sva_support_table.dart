// Generates the docs-site SVA support table from the measured probe matrix.
//
// The table is never written by hand: every row is what the open frontends
// did with one of the 51 probes in verification/fixtures/formal/sva_matrix/,
// measured by the real tools (tool/regenerate_formal_fixtures.sh writes
// captured/results.tsv; the engine canary re-measures it every month and
// fails when the measurement no longer matches the committed table).
//
// Usage:
//   dart run tool/generate_sva_support_table.dart            # write
//   dart run tool/generate_sva_support_table.dart --check    # exit 1 if stale
//   dart run tool/generate_sva_support_table.dart --check \
//       --results <measured.tsv>                             # canary
//
// Options:
//   --results <tsv>  probe, frontend, exit, cells (default: the committed
//                    sva_matrix/captured/results.tsv)
//   --build <tag>    the OSS CAD Suite build measured (default: from
//                    PROVENANCE.md)
//   --date <date>    the measurement date (default: from PROVENANCE.md)
//   --out <file>     default docs-site/generated/sva-support-table.md
//   --check          compare instead of writing: the full file against the
//                    committed one, or, with --results, the table rows only
//                    (a fresh measurement has a new date)

import 'dart:convert';
import 'dart:io';

const String kMatrixDir = 'verification/fixtures/formal/sva_matrix';
const String kProvenance = 'verification/fixtures/formal/PROVENANCE.md';
const String kDefaultOut = 'docs-site/generated/sva-support-table.md';

/// One measured probe: its expectation row and what each frontend did.
class SvaProbeRow {
  SvaProbeRow({
    required this.probe,
    required this.construct,
    required this.form,
    required this.constructClass,
    required this.builtinAccepted,
    required this.slangAccepted,
  });

  final String probe;
  final String construct;
  final String form;
  final String? constructClass;
  final bool? builtinAccepted;
  final bool? slangAccepted;
}

/// The rows, in the expectation file's order, from [expectedJson] and the
/// measured [resultsTsv].
List<SvaProbeRow> svaRows(String expectedJson, String resultsTsv) {
  final expected = jsonDecode(expectedJson) as Map<String, Object?>;
  final measured = <String, bool>{};
  for (final line in const LineSplitter().convert(resultsTsv).skip(1)) {
    final cols = line.split('\t');
    if (cols.length < 3) continue;
    measured['${cols[0]}|${cols[1]}'] = cols[2].trim() == '0';
  }
  return <SvaProbeRow>[
    for (final raw in expected['probes']! as List<Object?>)
      if (raw case final Map<String, Object?> probe)
        SvaProbeRow(
          probe: probe['probe']! as String,
          construct: probe['construct']! as String,
          form: probe['form']! as String,
          constructClass: probe['class'] as String?,
          builtinAccepted: measured['${probe['probe']}|builtin'],
          slangAccepted: measured['${probe['probe']}|slang'],
        ),
  ];
}

/// The measurement build and date recorded in PROVENANCE.md.
({String build, String date}) provenanceOf(String provenance) {
  final build = RegExp(
    r'^- `sva_matrix/captured/` build (\d{8})$',
    multiLine: true,
  ).firstMatch(provenance)?.group(1);
  final date = RegExp(
    r'^Regenerated (\d{4}-\d{2}-\d{2}) with:',
    multiLine: true,
  ).firstMatch(provenance)?.group(1);
  return (build: build ?? 'unknown', date: date ?? 'unknown');
}

String _cell(bool? accepted) => switch (accepted) {
  true => 'Accepted',
  false => 'Refused',
  null => 'Not measured',
};

String _form(SvaProbeRow row) => switch (row.form) {
  'temporal' => 'Temporal (${row.constructClass ?? 'other'})',
  'concurrent_boolean' => 'Clocked boolean property',
  'immediate' => 'Immediate assertion',
  'initial' => 'Initial-state constraint',
  _ => row.form,
};

/// Escapes a construct for a Markdown table cell.
String _code(String text) => '`${text.replaceAll('|', r'\|')}`';

/// The Markdown file.
String svaSupportTable(
  List<SvaProbeRow> rows, {
  required String build,
  required String date,
}) {
  final b = StringBuffer()
    ..writeln('<!-- Generated by tool/generate_sva_support_table.dart from')
    ..writeln('     verification/fixtures/formal/sva_matrix/. Do not edit. -->')
    ..writeln()
    ..writeln(
      'Measured $date on OSS CAD Suite build $build, one probe per row: '
      "Yosys's built-in frontend (`read_verilog -formal -sv`) and the "
      'yosys-slang plugin (`read_slang`), each followed by `prep`. A refused '
      'construct stops the run, and SimCrux reports the row as Did not run '
      'with the construct and its location. An accepted probe kept its one '
      'formal cell in every case: no property was dropped.',
    )
    ..writeln()
    ..writeln('| Construct | Form | Built-in frontend | yosys-slang |')
    ..writeln('|---|---|---|---|');
  for (final row in rows) {
    b.writeln(
      '| ${_code(row.construct)} | ${_form(row)} | '
      '${_cell(row.builtinAccepted)} | ${_cell(row.slangAccepted)} |',
    );
  }
  return b.toString();
}

Iterable<String> _tableRows(String text) =>
    const LineSplitter().convert(text).where((l) => l.startsWith('|'));

Future<void> main(List<String> args) async {
  String? option(String name) {
    final i = args.indexOf(name);
    return i >= 0 && i + 1 < args.length ? args[i + 1] : null;
  }

  final check = args.contains('--check');
  final resultsPath = option('--results');
  final out = option('--out') ?? kDefaultOut;
  final provenance = provenanceOf(File(kProvenance).readAsStringSync());
  final rows = svaRows(
    File('$kMatrixDir/sva_matrix.expected.json').readAsStringSync(),
    File(resultsPath ?? '$kMatrixDir/captured/results.tsv').readAsStringSync(),
  );
  final text = svaSupportTable(
    rows,
    build: option('--build') ?? provenance.build,
    date: option('--date') ?? provenance.date,
  );
  if (!check) {
    File(out)
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(text);
    stdout.writeln('wrote $out (${rows.length} probes)');
    return;
  }
  final committed = File(out).existsSync() ? File(out).readAsStringSync() : '';
  final same = resultsPath == null
      ? committed == text
      : _tableRows(committed).join('\n') == _tableRows(text).join('\n');
  if (same) {
    stdout.writeln('$out is current');
    return;
  }
  stderr.writeln(
    '$out does not match the ${resultsPath == null ? 'committed' : 'measured'} '
    'probe matrix. Regenerate the captures with '
    'tool/regenerate_formal_fixtures.sh, then run '
    'dart run tool/generate_sva_support_table.dart and commit both.',
  );
  exitCode = 1;
}
