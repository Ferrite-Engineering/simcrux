// Generates the docs-site list of LibreLane releases SimCrux reads as
// verified, from crux_flow's `kLibreLane30Verified`.
//
// The list is never written by hand: the reader's own constant is the single
// source, and test/static/librelane_verified_list_test.dart fails when the
// committed file stops matching it.
//
// Usage:
//   dart run tool/generate_librelane_verified_list.dart           # write
//   dart run tool/generate_librelane_verified_list.dart --check   # exit 1 if stale

import 'dart:io';

import 'package:crux_flow/crux_flow.dart';

const String kDefaultOut = 'docs-site/generated/librelane-verified.md';

/// The releases [range] holds, oldest first.
List<LibreLaneVersion> releasesIn(LibreLaneVersionRange range) {
  final first = range.first;
  final last = range.last;
  if (first.major != last.major || first.minor != last.minor) {
    throw StateError('A verified range stays inside one minor line.');
  }
  return <LibreLaneVersion>[
    for (var patch = first.patch; patch <= last.patch; patch++)
      LibreLaneVersion(first.major, first.minor, patch),
  ];
}

/// The Markdown file for [range].
String librelaneVerifiedList(LibreLaneVersionRange range) {
  final b = StringBuffer()
    ..writeln(
      '<!-- Generated by tool/generate_librelane_verified_list.dart from',
    )
    ..writeln("     crux_flow's kLibreLane30Verified. Do not edit. -->")
    ..writeln()
    ..writeln('| LibreLane release | How SimCrux reads it |')
    ..writeln('|---|---|');
  for (final v in releasesIn(range)) {
    b.writeln('| ${v.raw} | Verified |');
  }
  return b.toString();
}

Future<void> main(List<String> args) async {
  final text = librelaneVerifiedList(kLibreLane30Verified);
  final out = kDefaultOut;
  if (!args.contains('--check')) {
    File(out)
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(text);
    stdout.writeln('wrote $out');
    return;
  }
  final committed = File(out).existsSync() ? File(out).readAsStringSync() : '';
  if (committed == text) {
    stdout.writeln('$out is current');
    return;
  }
  stderr.writeln(
    '$out does not match kLibreLane30Verified. Run '
    'dart run tool/generate_librelane_verified_list.dart and commit it.',
  );
  exitCode = 1;
}
