import 'package:flutter_test/flutter_test.dart';
import 'package:simcrux/domain/models/sby_script.dart';

// The `.sby` job-file reader (VERIFICATION_GUIDE.md §18.3).
//
// It reads three facts — proof mode, depth and the task list — and
// deliberately understands nothing else. `sby` remains the authority on
// what a job file means; nothing here changes how a proof runs.

void main() {
  const bmc = '''
[options]
mode bmc
depth 20
append 0

[engines]
smtbmc boolector

[script]
read -formal democore.v
prep -top rvfi_testbench

[files]
democore.v
rvfi_macros.vh
''';

  group('options', () {
    test('mode and depth are read', () {
      final script = SbyScript.parse(bmc);
      expect(script.proofMode, 'bmc');
      expect(script.depth, 20);
      expect(script.tasks, isEmpty);
    });

    test('a timeout is read when the file sets one', () {
      expect(
        SbyScript.parse('[options]\nmode prove\ntimeout 900\n').timeoutSeconds,
        900,
      );
    });

    test('only the [options] section is consulted', () {
      // `depth` appearing in a script or a comment must not be mistaken
      // for the option.
      final script = SbyScript.parse('''
[options]
mode cover

[script]
depth 999
''');
      expect(script.proofMode, 'cover');
      expect(script.depth, isNull);
    });

    test('a task-scoped option still yields the unscoped default', () {
      final script = SbyScript.parse('''
[options]
mode bmc
deep: depth 40
''');
      expect(script.proofMode, 'bmc');
      expect(script.depth, 40);
    });

    test('comments and blank lines are ignored', () {
      final script = SbyScript.parse('''
# generated by genchecks.py

[options]
# the bound
mode bmc
depth 12
''');
      expect(script.depth, 12);
    });
  });

  group('tasks', () {
    test('a [tasks] section is enumerated in declaration order', () {
      final script = SbyScript.parse('''
[tasks]
basecase
induction

[options]
mode prove
''');
      expect(script.tasks, ['basecase', 'induction']);
    });

    test('only the first token of a task line names the task', () {
      expect(
        SbyScript.parse('[tasks]\nfast  small quick\nslow  large\n').tasks,
        ['fast', 'slow'],
      );
    });

    test('duplicates are collapsed', () {
      expect(SbyScript.parse('[tasks]\na\na\nb\n').tasks, ['a', 'b']);
    });
  });

  group('robustness', () {
    test('an empty or unusual file yields an all-null script, not a throw', () {
      expect(SbyScript.parse(''), const SbyScript());
      expect(SbyScript.parse('not a sby file at all'), const SbyScript());
    });

    test('a non-numeric depth is dropped rather than guessed at', () {
      expect(SbyScript.parse('[options]\ndepth lots\n').depth, isNull);
    });

    test('value semantics', () {
      expect(SbyScript.parse(bmc), SbyScript.parse(bmc));
      expect(SbyScript.parse(bmc).hashCode, SbyScript.parse(bmc).hashCode);
    });
  });

  // The corpus's own multi-task file: a task in a group, a scope by group,
  // and a negated scope. Expectations are what the file says, read by hand.
  const handshake = '''
[tasks]
prove
prove_bug prove
cover

[options]
prove: mode prove
cover: mode cover
depth 12

[engines]
prove: smtbmc yices
cover: smtbmc yices

[script]
prove_bug: read -formal -DBUG_ACK_LATE handshake_imm.sv
~prove_bug: read -formal handshake_imm.sv
prep -top handshake_imm

[files]
handshake_imm.sv
''';

  group('[engines] and [script]', () {
    test('engine lines are read in order, scope stripped', () {
      expect(SbyScript.parse(bmc).engines, ['smtbmc boolector']);
      expect(SbyScript.parse(handshake).engines, [
        'smtbmc yices',
        'smtbmc yices',
      ]);
    });

    test('script lines are read in order, scope stripped', () {
      expect(SbyScript.parse(bmc).script, [
        'read -formal democore.v',
        'prep -top rvfi_testbench',
      ]);
    });

    test('a task sees its own lines, its group lines, and a negated scope '
        'that does not name it', () {
      final script = SbyScript.parse(handshake);
      expect(script.scriptFor('prove_bug'), [
        'read -formal -DBUG_ACK_LATE handshake_imm.sv',
        'prep -top handshake_imm',
      ]);
      expect(script.scriptFor('prove'), [
        'read -formal handshake_imm.sv',
        'prep -top handshake_imm',
      ]);
      expect(script.scriptFor('cover'), [
        'read -formal handshake_imm.sv',
        'prep -top handshake_imm',
      ]);
    });

    test('a [tasks] line names its groups', () {
      final script = SbyScript.parse(handshake);
      expect(script.tasks, ['prove', 'prove_bug', 'cover']);
      expect(script.taskGroups['prove_bug'], ['prove']);
      expect(script.taskGroups['prove'], isEmpty);
    });
  });

  group('modeFor', () {
    test('a task takes the mode scoped to it or to its group', () {
      final script = SbyScript.parse(handshake);
      expect(script.modeFor('prove'), 'prove');
      expect(script.modeFor('prove_bug'), 'prove');
      expect(script.modeFor('cover'), 'cover');
    });

    test('a file without scopes gives every task its one mode', () {
      expect(SbyScript.parse(bmc).modeFor(null), 'bmc');
      expect(SbyScript.parse('$bmc\n[tasks]\na\n').modeFor('a'), 'bmc');
    });
  });

  group('assertionsDisabledFor', () {
    test("Yosys's -noassert is reported as noassert", () {
      final script = SbyScript.parse(
        '[script]\nread -formal -noassert top.sv\nprep -top top\n',
      );
      expect(script.assertionsDisabledFor(null), 'noassert');
      expect(script.assertionsDisabled, 'noassert');
    });

    test("yosys-slang's --ignore-assertions is reported as "
        'ignore_assertions', () {
      final script = SbyScript.parse(
        '[script]\nread_slang top.sv --top top --ignore-assertions\n',
      );
      expect(script.assertionsDisabledFor(null), 'ignore_assertions');
    });

    test('only the task whose script turns them off reports it', () {
      final script = SbyScript.parse(
        '[tasks]\nfast\nfull\n\n[script]\n'
        'fast: read -formal -noassert top.sv\n'
        'full: read -formal top.sv\n',
      );
      expect(script.assertionsDisabledFor('fast'), 'noassert');
      expect(script.assertionsDisabledFor('full'), isNull);
      expect(script.assertionsDisabled, 'noassert');
    });

    test('a script that keeps its assertions reports nothing', () {
      expect(SbyScript.parse(bmc).assertionsDisabled, isNull);
      expect(SbyScript.parse(handshake).assertionsDisabled, isNull);
    });
  });

  group('multiclockFor', () {
    test('multiclock on applies to every task, or to the one it scopes', () {
      expect(
        SbyScript.parse('[options]\nmode bmc\nmulticlock on\n').multiclockFor(
          null,
        ),
        isTrue,
      );
      final scoped = SbyScript.parse(
        '[tasks]\na\nb\n\n[options]\nmode bmc\na: multiclock on\n',
      );
      expect(scoped.multiclockFor('a'), isTrue);
      expect(scoped.multiclockFor('b'), isFalse);
    });

    test('off, or no line at all, is single-clock', () {
      expect(
        SbyScript.parse('[options]\nmulticlock off\n').multiclockFor(null),
        isFalse,
      );
      expect(SbyScript.parse(bmc).multiclockFor(null), isFalse);
      expect(SbyScript.parse(handshake).multiclockFor('prove_bug'), isFalse);
    });
  });
}
